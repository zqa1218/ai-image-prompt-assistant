/**
 * 分步生成线的三段契约：背景与景别陈设 → 身体互动特效 → 氛围层。
 * 第 2 步固定走参考图模式；有没有参考图决定用哪套引用规则。
 */
export function threeStepContract(input: TaskInput): string | null {
  if (input.workflow.id !== "refine-steps") return null;
  const referenceCount = input.images.filter(
    (image) => image.role === "reference",
  ).length;
  const step2 =
    referenceCount > 0
      ? `第2步是参考图模式，必须点名引用（本次共 ${referenceCount} 张参考图）：
- 这一段的第一句必须是「本步使用 REFERENCE_n，只借用它的……」，写清编号与只借用的方面
- 需要多张参考图时逐张说明各自只负责什么，不得含糊成「参考图里」
- 编号必须与图片清单里给出的编号、以及每张图标注的「分工」完全对应；没有分到这步需要的方面就不要引用它
- 这一步确实不需要参考图时，第一句写「本步不使用参考图」，并说明依据来自文字需求
- 参考图只提供它被指定的那部分信息；人物身份、原图空间与光影仍以 REFERENCE_0 为准
- 如果本步出现粒子、能量体、电弧、液滴这类特效，必须额外写清：粒子形态（颗粒状/丝缕状/烟雾状/电弧/液滴/光尘）、光影关系（自发光还是受光照亮、如何映亮周围皮肤与衣物）、发光颜色（主色、次色、是否有渐变或分色）`
      : `第2步本次没有参考图可引用，第一句写「本步不使用参考图」，特效只按文字需求描述；若出现粒子与能量体，同样要写清形态、光影与发光颜色`;

  const head = `只输出一个 json 对象，不要任何解释文字，结构如下：
{"prompt":"三段分步提示词，用【】标题分隔","channel":"一句「喂给谁」的建议","checklist":["提交前要确认的条目"]}

prompt 字段必须严格分成三段，按顺序排列，每段用独立一行的方括号标题开头，段与段之间空一行：
【第1步·背景与景别陈设】
【第2步·身体互动特效】
【第3步·氛围层】

三步的分工与硬约束（这是本次任务的核心，严格遵守）：
- 第1步合并处理背景与同景别陈设，必须写在同一个段落里、由同一次生成完成，不要拆成两次描述。写法固定为：先重建背景空间，再写陈设如何落在这个新背景上。先写背景、地面、天空或天花板的置换与新增，交代替换后的空间结构、地平线、透视、光源位置与明暗分布；紧接着写与角色同处一个景别、但不与身体直接接触的实体陈设（弹药箱、坐骑、座椅、屏风、地台、手办台、烛台、脚边道具），逐项写清方位、相对人物尺寸、支撑落点、接触阴影、投影方向与遮挡关系，并交代它们的色温与受光必须与新背景一致。
- 第1步不出现任何参考图字样，也不得出现 REFERENCE、素材图、图片编号或「与某图一致」。从参考图提炼到的信息要转写成物体本身的类别、外形、结构、材质、颜色与磨损。
- 第2步只写与角色身体互动、或紧贴身体并影响局部形体的特效与物体：能量体、粒子、武器光效、水、火、电、束缚身体的丝线绳索。写清贴在哪个部位、如何缠绕或发光、对局部衣料与皮肤的影响；不得改写第1步已确定的背景、光影与陈设。
- 第3步只写全局氛围层：雨、雾、体积光、空气颗粒、前景花瓣与树叶等散景。必须写清覆盖范围（全画面还是局部）、浓度或强度（极微量/适中/浓重）、方向与流动趋势，以及对已存在物体与人物造成的具体影响（打湿、反光、压暗、边缘发雾、前景遮挡）；不得改变前两步已确定的任何物体与人物形态。

每段都要能单独提交，因此：
- 每段开头先写明这一步用哪张图作为输入（第1步用原始底图，第2步用第1步输出图，第3步用第2步输出图）、编辑的是哪个区域；
- 每段都要重申保持人物身份、五官、肤质、发型、服装形制、动作与接触点不变，但不要重复其它步骤的具体内容；
- 禁止把一个物体写进两个步骤；若它跨层，只写进主要影响的那一层，另一层用一句「已在前一步确定，保持不变」带过；
- 输出前逐段核对参考图编号与「参考图分工」是否一致，不一致就先改对再输出；
- 不要输出分析过程，不要在 prompt 字段里加代码围栏，不要使用「第一步」「第二步」之外的编号体系。`;

  return `${head}\n\n${step2}`;
}
