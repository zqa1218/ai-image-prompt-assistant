import { parseMulti } from '../multiValue.ts'
import type { TaskInput } from './task.ts'

export function usesPaintedHair(input: TaskInput): boolean {
  return input.workflow.id === 'refine' && parseMulti(input.intake.taskType).includes('厚涂修发')
}

