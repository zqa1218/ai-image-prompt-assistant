/** 仅在用户选择厚涂修发时注入；各阶段保留现有可解析的输出协议。 */
export function hairTask(input: TaskInput, extract = false): string {
  if (!usesPaintedHair(input)) return ''
  const step = extract
    ? '本轮只看参考图：按每张图实际职责提取刘海、脸侧发、后脑主发体、主发束数量、束结/束带、尾束、发色和质感。结构归入元素，发丝归入材质，发色归入色调；不迁移背景或人物身份，不假设未附带的底图。错误结果图只用于识别错误，选区图只用于边界，不作为新发型标准。'
    : input.stage.id === 'analyze'
      ? '本轮仅分析底图：头部朝向、已有刘海、后脑、肩背、帽子/手臂遮挡、可用空间、裁切、受光、景深和已认可区域。未附带参考图，不推断参考发束数量；此阶段只陈述事实。'
      : input.stage.id === 'direction'
        ? '方向建议只在允许模式内改变走势、展开幅度与动态，不通过增加主发束制造差异。严格复刻时仅比较相机投影和自然遮挡；每个方向写清发根接入、画面左/右走向、发量、发尾与遮挡。'
        : '结合底图和参考图确定一个具体走势：发根从哪里接出、肩前/肩后、画面左/右/下/后、主发量分区、发尾收尖/分叉/轻扬、束结位置及帽子/手臂/肩/衣服前后关系。已选方向与用户认可区域保持不变。'
  return `## 厚涂修发专项（本次选中才生效）
你负责分析和编写文字提示词，禁止生成或编辑图片。
模式：${input.intake.hairMode || '参考适配设计'}。当轮明确要求优先；严格复刻不新增结构，默认参考适配仅调整空间走势，局部优化只改失败维度，自由设计仅在用户明确选择或授权时生效。
${step}
底图 REFERENCE_0 决定身份、真实摄影几何与保留区域；参考图 REFERENCE_1...N 按用户分工决定可确认的头发结构。锁定项优先于参考；未锁定发色才可按参考调整并匹配底图受光。与通用“发型不变”冲突时，仅允许本轮明确授权的头发区域变化。无参考时沿用底图可见结构，不编造参考或束结；参考冲突关键时最多问一个优先级问题。
按刘海/脸侧、后脑主发体、发根连接、束结、尾束依次判断；背面看不到的正面结构只保守推断。主发束数量不因增加细丝而增加；两片资产不能变第三组主束；背后低位束结不能为展示而移到胸前。允许发尾自然出画，不能缩小人物或扩图。
质感依次是大束灰度块面塑形、中层连续丝束、细亮断续且亮度不一的单根丝状高光。厚涂塑造体积，细丝表达材质；不是平涂插画、塑料丝带、死白宽光带或星点粒子。光向、色温、锐度、景深、颗粒延续底图。
仅修改授权区域，锁定人物五官、妆容、表情、姿态、服装、非头发道具、背景、机位和整体光影；发根、帽檐、耳侧、手臂与肩衣不能穿模。禁止项针对本次真实风险，不机械禁止参考原设的双马尾、卷发或粗束。
失败反馈先区分结构、发量、动态、遮挡和质感：结构正确就只修纹理高光，几何根本跑偏才建议回原底图；保留已认可的刘海和局部。
最终生成和迭代的完整提示词必须逐字包含这三句（分析和参考拆解阶段无需输出）：
${HAIR_TEXTURE}
输出前自检：图像分工、数量与束结证据、走势与遮挡、授权范围、三层质感、三句固定文案、摄影融合、针对性禁止项。成品不留括号占位符。`
}

